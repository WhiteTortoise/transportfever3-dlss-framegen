# Builds dist\TF3-FrameGen-Setup.exe: the mod DLL embedded, NVIDIA's files
# pinned by SHA-256 and downloaded from NVIDIA's GitHub at install time.
$ErrorActionPreference = 'Stop'
$root = $PSScriptRoot

& (Join-Path $root 'build.ps1')
if ($LASTEXITCODE) { exit $LASTEXITCODE }

$slVersion = '2.14.1'
$zipName = "streamline-sdk-v$slVersion.zip"
$zip = Join-Path $root "external\dl\$zipName"
$bin = Join-Path $root 'external\streamline\bin\x64'
$files = 'sl.interposer.dll', 'sl.common.dll', 'sl.dlss_g.dll', 'sl.reflex.dll', 'sl.pcl.dll', 'nvngx_dlssg.dll',
         'NvLowLatencyVk.dll'

$entries = foreach ($f in $files) {
    $h = (Get-FileHash (Join-Path $bin $f) -Algorithm SHA256).Hash
    "            new RuntimeFile(`"$f`", `"$h`"),"
}
$zipHash = (Get-FileHash $zip -Algorithm SHA256).Hash
$zipSize = (Get-Item $zip).Length

@"
// Generated by build_installer.ps1 - do not edit.
namespace Tf3FrameGen
{
    static class Generated
    {
        public class RuntimeFile
        {
            public readonly string Name, Sha256;
            public RuntimeFile(string name, string sha256) { Name = name; Sha256 = sha256; }
        }

        public const string StreamlineVersion = "$slVersion";
        public const string StreamlineZipName = "$zipName";
        public const string StreamlineUrl = "https://github.com/NVIDIA-RTX/Streamline/releases/download/v$slVersion/$zipName";
        public const string StreamlineZipSha256 = "$zipHash";
        public const long StreamlineZipSize = $zipSize;

        public static readonly RuntimeFile[] Files =
        {
$($entries -join "`r`n")
        };
    }
}
"@ | Set-Content (Join-Path $root 'installer\Generated.cs') -Encoding UTF8

$dist = Join-Path $root 'dist'
New-Item -ItemType Directory -Force $dist | Out-Null
$csc = Join-Path $env:WINDIR 'Microsoft.NET\Framework64\v4.0.30319\csc.exe'
& $csc /nologo /target:winexe /optimize+ "/out:$dist\TF3-FrameGen-Setup.exe" `
    "/win32manifest:$root\installer\app.manifest" `
    "/resource:$root\build\winhttp.dll,tf3fg.winhttp.dll" `
    /r:System.IO.Compression.dll /r:System.IO.Compression.FileSystem.dll /r:System.Management.dll `
    /r:System.Windows.Forms.dll /r:System.Drawing.dll `
    "$root\installer\Installer.cs" "$root\installer\Generated.cs"
if ($LASTEXITCODE) { exit $LASTEXITCODE }
Copy-Item (Join-Path $root 'README.md') $dist -Force
Get-Item "$dist\TF3-FrameGen-Setup.exe" | Select-Object Name, Length
