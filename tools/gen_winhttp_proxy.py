"""Generate pass-through export stubs for a winhttp.dll proxy.

Reads the export table of the system winhttp.dll and writes:
  src/proxy/winhttp.def          - module definition with identical names/ordinals
  src/proxy/winhttp_stubs.asm    - x64 MASM jump stubs (jmp [g_winhttpReal + i*8])
  src/proxy/winhttp_exports.inc  - table used to resolve the real functions at load
"""
import os
import struct
import sys


def rva_to_off(sections, rva):
    for va, vsz, raw, rsz in sections:
        if va <= rva < va + max(vsz, rsz):
            return rva - va + raw
    raise ValueError("rva %x not in any section" % rva)


def cstr(data, off):
    return data[off:data.index(b"\0", off)].decode("ascii")


def read_exports(path):
    data = open(path, "rb").read()
    pe = struct.unpack_from("<I", data, 0x3C)[0]
    nsec = struct.unpack_from("<H", data, pe + 6)[0]
    optsz = struct.unpack_from("<H", data, pe + 20)[0]
    opt = pe + 24
    ddir = opt + 112  # PE32+
    exp_rva, exp_size = struct.unpack_from("<II", data, ddir)
    sections = []
    for i in range(nsec):
        vsz, va, rsz, raw = struct.unpack_from("<IIII", data, opt + optsz + i * 40 + 8)
        sections.append((va, vsz, raw, rsz))
    e = rva_to_off(sections, exp_rva)
    base, nfuncs, nnames, funcs_rva, names_rva, ords_rva = struct.unpack_from("<IIIIII", data, e + 16)
    funcs = rva_to_off(sections, funcs_rva)
    names = rva_to_off(sections, names_rva)
    ords = rva_to_off(sections, ords_rva)
    by_index = {}
    for i in range(nnames):
        name = cstr(data, rva_to_off(sections, struct.unpack_from("<I", data, names + i * 4)[0]))
        idx = struct.unpack_from("<H", data, ords + i * 2)[0]
        by_index[idx] = name
    out = []
    for idx in range(nfuncs):
        if struct.unpack_from("<I", data, funcs + idx * 4)[0] == 0:
            continue
        out.append((base + idx, by_index.get(idx)))
    return out


def main():
    src = sys.argv[1] if len(sys.argv) > 1 else r"C:\Windows\System32\winhttp.dll"
    outdir = sys.argv[2]
    os.makedirs(outdir, exist_ok=True)
    exports = read_exports(src)

    with open(os.path.join(outdir, "winhttp.def"), "w", newline="\n") as f:
        f.write("LIBRARY winhttp\nEXPORTS\n")
        for i, (ordinal, name) in enumerate(exports):
            if name:
                f.write("    %s=ProxyStub_%d @%d\n" % (name, i, ordinal))
            else:
                f.write("    ProxyStub_%d @%d NONAME\n" % (i, ordinal))

    with open(os.path.join(outdir, "winhttp_stubs.asm"), "w", newline="\n") as f:
        f.write("; generated by gen_winhttp_proxy.py - do not edit\n")
        f.write("extern g_winhttpReal:qword\n.code\n")
        for i, _ in enumerate(exports):
            f.write("ProxyStub_%d proc\n    jmp qword ptr [g_winhttpReal + %d]\nProxyStub_%d endp\n" % (i, i * 8, i))
        f.write("end\n")

    with open(os.path.join(outdir, "winhttp_exports.inc"), "w", newline="\n") as f:
        f.write("// generated by gen_winhttp_proxy.py - do not edit\n")
        f.write("// { ordinal, name or nullptr }\n")
        for ordinal, name in exports:
            f.write('{ %d, %s },\n' % (ordinal, '"%s"' % name if name else "nullptr"))

    print("%d exports (%d by ordinal only)" % (len(exports), sum(1 for _, n in exports if not n)))


main()
